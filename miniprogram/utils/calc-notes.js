/**
 * 把某条计算器的说明转成可渲染的 blocks
 *
 * 小程序 formula 页与网页详情页共用，保证两端的小节标题完全一致。
 * @param {string} id 计算器 id
 * @returns {Array<{kind:string,text:string}>}
 */
function notesBlocks(id) {
  const n = CALC_NOTES[id];
  if (!n) return [];
  const out = [];
  if (n.use) {
    out.push({ kind: 'h', text: '这个指标是干什么用的' });
    out.push({ kind: 'text', text: n.use });
  }
  if (n.std) {
    out.push({ kind: 'h', text: '参考标准 / 正常值' });
    out.push({ kind: 'text', text: n.std });
  }
  if (n.tip) {
    out.push({ kind: 'h', text: '判读要点与常见陷阱' });
    out.push({ kind: 'text', text: n.tip });
  }
  return out;
}

module.exports = { CALC_NOTES: CALC_NOTES, notesBlocks: notesBlocks };
